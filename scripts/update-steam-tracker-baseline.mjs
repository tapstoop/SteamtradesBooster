import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const ENDPOINT = 'https://steam-tracker.com/api?action=GetAppListV3';
const OUTPUT = new URL('../background/steam-tracker-baseline.js', import.meta.url);
const SUPPORTED = new Set([1, 3, 20]);

function normalizeTitle(title) {
  return title.toLowerCase()
    .replace(/[™®:'.!?,\u2013\u2014]/g, '')
    .replace(/-/g, ' ')
    .replace(/[•●○◆►*]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const response = await fetch(ENDPOINT, {
  cache: 'no-store',
  credentials: 'omit',
  redirect: 'error',
  referrerPolicy: 'no-referrer',
  headers: { Accept: 'application/json' },
});
if (!response.ok) throw new Error(`Steam Tracker returned HTTP ${response.status}`);
const bytes = new Uint8Array(await response.arrayBuffer());
const payload = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes));
if (payload?.success !== true || !Array.isArray(payload.removed_apps)) throw new Error('Unexpected Steam Tracker schema');

const byId = Object.create(null);
for (const record of payload.removed_apps) {
  const categoryId = Number(record?.category_id);
  const appId = String(record?.appid ?? '');
  const name = String(record?.name ?? '').trim();
  if (record?.type !== 'game' || !SUPPORTED.has(categoryId) || !/^\d+$/.test(appId) || !name) continue;
  const current = byId[appId];
  if (!current || categoryId === 20 || (categoryId === 3 && current.categoryId === 1)) {
    byId[appId] = { categoryId, name };
  }
}

const byTitle = Object.create(null);
const categoryCounts = { removed_delisted: 0, removed_disabled: 0, removed_banned: 0 };
for (const [appId, record] of Object.entries(byId)) {
  const key = normalizeTitle(record.name);
  if (!byTitle[key]) byTitle[key] = [];
  byTitle[key].push(appId);
  const status = record.categoryId === 1 ? 'removed_delisted' : record.categoryId === 3 ? 'removed_disabled' : 'removed_banned';
  categoryCounts[status]++;
}
for (const ids of Object.values(byTitle)) ids.sort((a, b) => Number(a) - Number(b));

const generatedAt = Date.now();
const revision = createHash('sha256').update(bytes).digest('hex');
const snapshot = {
  schemaVersion: 3,
  fetchedAt: generatedAt,
  revision: `baseline:${revision}`,
  byId,
  byTitle,
  itemCount: Object.keys(byId).length,
  rawItemCount: payload.removed_apps.length,
  unknownCategoryCount: 0,
  categoryCounts,
};
const meta = {
  generatedAt,
  revision,
  sourceByteLength: bytes.byteLength,
  rawItemCount: payload.removed_apps.length,
  itemCount: snapshot.itemCount,
  categoryCounts,
};

const source = `// Generated by scripts/update-steam-tracker-baseline.mjs.\n`
  + `export const STEAM_TRACKER_BASELINE_META = ${JSON.stringify(meta)};\n`
  + `export const STEAM_TRACKER_BASELINE_SNAPSHOT = ${JSON.stringify(snapshot)};\n`;
await writeFile(OUTPUT, source);
console.log(`Wrote ${snapshot.itemCount} supported apps from ${payload.removed_apps.length} records (${bytes.byteLength} bytes)`);
